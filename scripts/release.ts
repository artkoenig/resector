// Release helpers (NFR-5): compile targets, tag check, asset naming.
// Pure; scripts/build.ts does the I/O.

export const TARGETS = ['darwin-arm64', 'darwin-x64', 'linux-x64', 'linux-arm64'] as const;
export type Target = (typeof TARGETS)[number];

export function versionFromTag(tag: string, pkgVersion: string): string {
  if (!tag.startsWith('v')) throw new Error(`tag "${tag}" must look like v<version>`);
  if (tag.slice(1) !== pkgVersion)
    throw new Error(`tag ${tag} does not match package.json version ${pkgVersion}`);
  return pkgVersion;
}

export const assetName = (version: string, target: Target) =>
  `resector-v${version}-${target}.tar.gz`;

const asset = (version: string, target: Target, sums: string) => {
  const name = assetName(version, target);
  const sha = sums.split('\n').map(l => l.split(/\s+/)).find(([, file]) => file === name)?.[0];
  if (!sha || !/^[0-9a-f]{64}$/.test(sha)) throw new Error(`no checksum for ${name} in SHA256SUMS`);
  return `      url "https://github.com/artkoenig/resector/releases/download/v${version}/${name}"
      sha256 "${sha}"`;
};

// The Homebrew formula for the release binaries; sums: the release's SHA256SUMS.
export const formula = (version: string, sums: string) => `# Generated by scripts/formula.ts in artkoenig/resector; do not edit.
class Resector < Formula
  desc "Coding agent for local LLMs that lets you manage the context"
  homepage "https://github.com/artkoenig/resector"
  license "MIT"

  on_macos do
    on_arm do
${asset(version, 'darwin-arm64', sums)}
    end
    on_intel do
${asset(version, 'darwin-x64', sums)}
    end
  end

  on_linux do
    on_arm do
${asset(version, 'linux-arm64', sums)}
    end
    on_intel do
${asset(version, 'linux-x64', sums)}
    end
  end

  def install
    bin.install "resector"
  end

  test do
    assert_match version.to_s, shell_output("#{bin}/resector --version")
  end
end
`;
